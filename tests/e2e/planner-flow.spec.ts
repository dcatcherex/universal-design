import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import path from 'node:path'

test('completes a Thai project, proposal, review, save, round-trip and report', async ({ page }) => {
  await page.addInitScript(() => { window.print = () => undefined })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await page.getByRole('button', { name: 'สร้างโครงการใหม่' }).click()
  await page.getByLabel('ชื่อโครงการ').fill('บ้านครอบครัวทดลอง')
  await page.getByLabel('กว้าง (ม.)').fill('6')
  await page.getByLabel('ลึก (ม.)').fill('5')
  await page.getByRole('button', { name: 'เริ่มโครงการ' }).click()

  await expect(page.locator('.canvas-caption')).toContainText('6.00 × 5.00 m')
  await page.getByRole('button', { name: 'โต๊ะกลาง, 1100 × 600 × 450 mm' }).click()
  const canvas = page.locator('svg[aria-label^="แผนผังห้อง"]')
  await canvas.scrollIntoViewIfNeeded()
  const box = await canvas.boundingBox()
  if (!box) throw new Error('The room plan is not visible')
  await page.mouse.click(box.x + box.width * 0.5, box.y + box.height * 0.5)
  await expect(page.locator('.item-list .item-list-row')).toHaveCount(1)
  await page.screenshot({ path: path.resolve('docs/handoff/evidence/m4-thai-current-2d.png') })
  await page.getByRole('button', { name: 'สร้างแบบเสนอปรับปรุง' }).click()
  await page.getByRole('button', { name: 'หลังปรับปรุง' }).click()
  const table = page.locator('[data-item-id^="item-"]')
  await table.focus()
  await table.press('ArrowRight')
  await page.locator('.item-list').getByRole('button', { name: /โต๊ะกลาง/ }).click()
  const x = page.getByLabel('ตำแหน่ง X (ซม.)')
  await x.fill('๓๕๐')
  await expect(table).toHaveAttribute('data-x-mm', '3500')
  await page.screenshot({ path: path.resolve('docs/handoff/evidence/m4-thai-proposed-2d.png') })
  await page.getByRole('button', { name: 'ก่อนปรับปรุง' }).click()
  await expect(page.locator('[data-item-id^="item-"]')).toHaveAttribute('data-x-mm', '3000')
  await page.getByRole('button', { name: 'หลังปรับปรุง' }).click()
  await page.getByRole('tab', { name: 'จุดที่ควรปรับปรุง' }).click()
  await expect(page.locator('[data-rule-id="G04"][data-check-status="not-evaluated"]')).toBeVisible()

  await page.getByRole('button', { name: 'ผู้ให้คำปรึกษา' }).click()
  await expect(page.getByText(/ไม่ใช่ข้อกำหนดทางกฎหมาย/)).toBeVisible()
  await page.getByLabel('เป้าหมายความกว้างแนวทางเดิน (ซม.)').fill('90')
  await page.getByLabel('ผู้บันทึก').nth(0).fill('ที่ปรึกษาทดสอบ')
  await page.getByLabel('เหตุผลของเป้าหมายโครงการนี้').nth(0).fill('เป้าหมายเฉพาะครัวเรือน')
  await page.getByRole('button', { name: 'บันทึกเป้าหมาย' }).nth(0).click()
  await page.getByRole('tab', { name: 'จุดที่ควรปรับปรุง' }).click()
  await page.getByRole('button', { name: 'วาดบนแผนผัง' }).click()
  await canvas.click({ position: { x: 130, y: 250 } })
  await canvas.click({ position: { x: 440, y: 250 } })
  await page.getByRole('button', { name: 'จบแนวทางเดิน' }).click()
  await expect(page.locator('[data-overlay-id^="route-"]')).toHaveCount(1)
  await expect(page.locator('[data-rule-id="G04"]').filter({ hasText: 'เป้าหมายเฉพาะโครงการ' }).first()).toBeVisible()

  await page.locator('[data-rule-id="G04"]').getByRole('button', { name: 'สร้างร่างข้อเสนอแนะ' }).click()
  const editor = page.locator('.recommendation-editor')
  await editor.getByLabel('หัวข้อ').fill('ปรับตำแหน่งโต๊ะ')
  await editor.getByLabel('เหตุผลที่อาจช่วยได้').fill('ทางเดินที่วางทับกับโต๊ะ')
  await editor.getByLabel('ขั้นตอนที่แนะนำ').fill('หารือกับครอบครัวก่อนเคลื่อนย้าย')
  await editor.getByLabel('สถานะ').selectOption('accepted')
  await editor.getByRole('button', { name: 'เพิ่มประมาณการ' }).first().click()
  await editor.getByLabel('ต่ำ (บาท)').fill('100.00')
  await editor.getByLabel('สูง (บาท)').fill('250.00')
  await editor.getByLabel('แหล่งที่มาหรือหมายเหตุประมาณการ').fill('ตัวอย่างสมมติสำหรับทดสอบ')
  await editor.getByLabel('วันที่ประมาณการ').fill('2026-09-28')
  await editor.getByRole('button', { name: 'บันทึกข้อเสนอแนะ' }).click()
  await expect(page.getByText(/ยอดรวมย่อยที่ทราบ: 100–250 บาท/)).toBeVisible()
  await page.getByLabel('ชื่อผู้ทบทวน (กรอกเอง)').fill('ผู้ทบทวนทดสอบ')
  await page.getByRole('button', { name: 'บันทึกการทบทวนสำหรับฉบับนี้' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'ทบทวนฉบับปัจจุบันแล้ว' })).toBeVisible()

  await expect(page.locator('.project-menu-wrap .save-state')).toHaveText('บันทึกบนอุปกรณ์นี้แล้ว', { timeout: 7000 })
  await page.reload()
  await page.getByRole('button', { name: /ทำโครงการต่อ/ }).click()
  await page.getByRole('button', { name: 'หลังปรับปรุง' }).click()
  await expect(page.locator('[data-item-id^="item-"]')).toHaveAttribute('data-x-mm', '3500')
  const projectDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'ไฟล์โครงการ' }).click()
  await page.getByRole('menuitem', { name: 'ดาวน์โหลดไฟล์โครงการ' }).click()
  const download = await projectDownload
  const project = JSON.parse(await readFile((await download.path())!, 'utf8')) as { title: string; current: { items: Array<{ id: string; center: { xMm: number } }> }; proposed: { items: Array<{ id: string; center: { xMm: number } }> } }
  expect(project.title).toBe('บ้านครอบครัวทดลอง')
  expect(project.current.items[0]?.center.xMm).toBe(3000)
  expect(project.proposed.items[0]?.center.xMm).toBe(3500)

  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'ไฟล์โครงการ' }).click()
  await page.getByRole('menuitem', { name: 'เปิดไฟล์โครงการ' }).click()
  await page.locator('input[type="file"]').setInputFiles((await download.path())!)
  await expect(page.locator('[data-item-id^="item-"]')).toHaveAttribute('data-x-mm', '3000')
  await page.getByRole('button', { name: 'หลังปรับปรุง' }).click()
  await expect(page.locator('[data-item-id^="item-"]')).toHaveAttribute('data-x-mm', '3500')

  const report = page.getByRole('button', { name: 'ส่งออก' })
  await report.click()
  await page.getByRole('menuitem', { name: 'ดูตัวอย่างรายงานสำหรับพิมพ์' }).click()
  await expect(page.getByRole('dialog', { name: 'รายงานการปรับบ้าน' })).toContainText('บ้านครอบครัวทดลอง')
  await page.getByRole('button', { name: 'พิมพ์ / บันทึกเป็น PDF' }).click()
  await expect.poll(() => page.locator('.report-dialog').evaluate((element) => (element as HTMLElement).style.width)).toBe('186mm')
  await page.emulateMedia({ media: 'print' })
  await page.pdf({ path: path.resolve('docs/handoff/evidence/m4-thai-report.pdf'), printBackground: true, preferCSSPageSize: true })
})
